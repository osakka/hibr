const size_t he_n = sizeof he_off / sizeof he_off[0];

/* The characters a named reference stands for, by its exact name, or 0. */
const char *he_find(const char *nm, size_t len, int *legacy)
{
	size_t lo = 0, hi = he_n, mid, k;
	const char *e;
	int c;

	while (lo < hi) {
		mid = (lo + hi) / 2;
		e = he_blob + (he_off[mid] & 0x7fff);
		k = strlen(e);
		c = memcmp(e, nm, k < len ? k : len);
		if (!c)
			c = (k > len) - (k < len);
		if (c < 0)
			lo = mid + 1;
		else if (c > 0)
			hi = mid;
		else {
			if (legacy)
				*legacy = !!(he_off[mid] & 0x8000);
			return e + k + 1;
		}
	}
	return 0;
}
